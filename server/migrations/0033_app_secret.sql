--
-- **PB が初回に生成する暗号鍵の置き場である。** tls_certificate（6.15）の
-- 秘密鍵を AES-256-GCM で暗号化するのに使う。
--
-- ── なぜ DB に置くのか ──────────────────────────────────
--
-- **利用者の操作を要らなくするためである**（利用者の決定、2026-09-12）。
-- **環境変数を必須にすると、証明書を1枚登録するために端末と再起動が必要になり**、
-- 「設定は WebGUI を第一の口とする」という方針（憲章「判断の記録」）と矛盾する。
-- **stg で利用者が「貼り付けできない」として踏んだ。**
--
-- **ファイルに置く案は K8s で壊れる。** Pod ごとに違う鍵ができ、互いに復号できない。
--
-- ── 代償を隠さない ──────────────────────────────────────
--
-- **既定では pg_dump に鍵と暗号文の両方が入る。** 暗号化の目的はバックアップや
-- レプリカの持ち出しから守ることなので、**既定ではその保護が効かない。**
-- PB_SECRET_KEY を与えればこの表を読まない。**効かないことを画面に出す**のが、
-- この判断を成立させる条件である。

-- +goose Up

-- key_id を主キーにするのは、**鍵を交換する日に2行目が要る**ためである
-- （古い鍵で暗号化された行が残っているあいだ）。いまは 'generated' の1行だけを使う。
--
-- **32バイトであることを CHECK で縛る。** AES-256-GCM の鍵長で、外れた行は
-- アプリ側でも弾かれるが、**入れられないようにするほうが早く気づける。**
CREATE TABLE app_secret (
  key_id      text PRIMARY KEY,
  secret      bytea NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT app_secret_len CHECK (octet_length(secret) = 32)
);

COMMENT ON TABLE app_secret IS
  'PB が生成した暗号鍵（Design.md 6.6.1）。PB_SECRET_KEY を与えたときは読まない';
