import { expect, test } from '@playwright/test'
import { mockEditingTicket } from './fixtures/ticket-editing'

for (const width of [600, 900, 1440]) {
  test(`close saves the description and cancel stays explicit at ${width}px`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 900 })
    const state = await mockEditingTicket(page, 'ja')
    await page.goto('/p/demo/tickets/1')
    await page.getByTitle('クリックして説明を編集').click()
    const editor = page.locator('.cm-content')
    await editor.fill('日本語の説明\n\n長い説明の保存を確認します。')
    const block = page.locator('section').filter({ has: editor })
    await expect(block.getByRole('button', { name: '保存', exact: true })).toHaveCount(0)
    await expect(block.getByText('編集を終えると自動保存されます')).toBeVisible()
    await block.locator('.preview').click()
    await expect(editor).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath(`autosave-${width}.png`), fullPage: true })
    await page.getByRole('button', { name: '詳細を閉じる' }).click()
    await expect(page).toHaveURL(/\/backlog/)
    expect(state.patches).toHaveLength(1)
    expect(state.items[0].body_md).toBe('日本語の説明\n\n長い説明の保存を確認します。')
    await page.getByRole('link', { name: '配置確認', exact: true }).click()
    await page.getByTitle('クリックして説明を編集').click()
    await editor.fill('取り消す下書き')
    await editor.press('Escape')
    await expect(editor).toHaveCount(0)
    expect(state.patches).toHaveLength(1)
    await page.getByTitle('クリックして説明を編集').click()
    await page.getByRole('button', { name: '取消', exact: true }).click()
    await expect(editor).toHaveCount(0)
    expect(state.patches).toHaveLength(1)
  })
}

test('switch, close and retry keep the draft after a failed save', async ({ page }) => {
  const state = await mockEditingTicket(page, 'ja', { failures: 1 })
  await page.goto('/p/demo/tickets/1')
  await page.getByTitle('クリックして説明を編集').click()
  await page.locator('.cm-content').fill('失敗しても残る下書き')
  await page.getByRole('link', { name: '別のチケット', exact: true }).click()
  await expect(page).toHaveURL(/tickets\/1/)
  await expect(page.locator('.cm-content')).toHaveText('失敗しても残る下書き')
  await expect(page.getByRole('alert').filter({ hasText: 'ほかの変更と競合しました' })).toBeVisible()
  await page.getByRole('button', { name: '再試行', exact: true }).click()
  await expect(page.locator('.cm-content')).toHaveCount(0)
  await page.getByRole('link', { name: '別のチケット', exact: true }).click()
  await expect(page).toHaveURL(/tickets\/2/)
  expect(state.patches).toHaveLength(2)
  expect(state.patches.every(p => p.seq === 1)).toBe(true)
  expect(state.items[0].body_md).toBe('失敗しても残る下書き')
})

test('typing during a save is saved again before navigation, without duplicate requests', async ({ page }) => {
  let release!: () => void
  const held = new Promise<void>(resolve => { release = resolve })
  let calls = 0
  const state = await mockEditingTicket(page, 'ja', { beforePatch: () => ++calls === 1 ? held : Promise.resolve() })
  await page.goto('/p/demo/tickets/1')
  await page.getByTitle('クリックして説明を編集').click()
  const editor = page.locator('.cm-content')
  await editor.fill('最初の下書き')
  await page.getByRole('button', { name: '詳細を閉じる' }).click()
  await expect.poll(() => state.patches.length).toBe(1)
  await expect(page).toHaveURL(/tickets\/1/)
  await editor.fill('保存中に追加した内容')
  await editor.press('Escape')
  await expect(editor).toBeVisible()
  release()
  await expect(page).toHaveURL(/\/backlog/)
  expect(state.patches.map(p => p.body.body_md)).toEqual(['最初の下書き', '保存中に追加した内容'])
  expect(state.items[0].body_md).toBe('保存中に追加した内容')
  expect(state.patches[0].match).not.toBe(state.patches[1].match)
})

test('unchanged description does not PATCH and focus outside saves', async ({ page }) => {
  const state = await mockEditingTicket(page, 'ja')
  await page.goto('/p/demo/tickets/1')
  await page.getByTitle('クリックして説明を編集').click()
  await page.getByRole('button', { name: '詳細を閉じる' }).click()
  await expect(page).toHaveURL(/\/backlog/)
  expect(state.patches).toHaveLength(0)
  await page.getByRole('link', { name: '配置確認', exact: true }).click()
  await page.getByTitle('クリックして説明を編集').click()
  await page.locator('.cm-content').fill('外へ移って保存')
  await page.locator('.block-title').filter({ hasText: '参考リンク' }).click()
  await expect(page.locator('.cm-content')).toHaveCount(0)
  expect(state.items[0].body_md).toBe('外へ移って保存')
})
