/**
 * URL の見せ方（`GuiDesign.md` 5.5 / 5.9.1）。
 *
 * PB が受け取る URL には**ブラウザから開けないもの**が混じる。リポジトリの
 * SSH 形式（`git@host:org/repo.git`）がそれで、リンクにしてもクリックで何も
 * 起きない。**開けるものだけをリンクにし、それ以外は文字列として出して
 * コピーできる状態にとどめる。**
 *
 * **判定の正本をここに1つ置く**（手順17c で切り出した）。同じ規則を使う場所が
 * 2つある——プロジェクト設定のリポジトリ表（5.9.1）と、チケット詳細の
 * コード・参考リンク（5.5）。写しを持つと、同じ文字列が画面によって
 * リンクになったりならなかったりする。
 */

/**
 * ブラウザで開ける URL か。
 *
 * **`http://` も真とする。** この規則が線を引いている理由は「開けるかどうか」で
 * あってスキームの安全性ではなく、社内 wiki や開発中のサーバは `http://` で
 * 出てくる（`GuiDesign.md` 5.9.1）。Slack・Teams・SharePoint のような
 * ファイルサービスへのリンクもここを通る。
 */
export function isWebUrl(url: string | null | undefined): boolean {
  if (url == null) return false
  return /^https?:\/\//i.test(url.trim())
}
